#!/usr/bin/env python3
"""Copy the glasses radar code into the course template (flat folder).

The template compiles app_program/*.c and app_program/*/*.c only (one
folder level) and finds headers next to the .c file, so every radar file
goes into one folder: app_program/subsystem5/. Three things are generated:
  - subsystem5.c, the shim with the names usermain() calls;
  - the one-line template change DEVCNF_USE_SER 0 in config/config_device.h
    (the radar owns the UART0 interrupt, see docs/rtos_port_notes.md);
  - nothing else in the template is touched.

Usage: python3 tools/export_to_template.py [template-root]
Without an argument, soup/utkernel (SOUP, never edited) is copied to
build/utkernel and the radar is exported there. With an argument, that
template tree (for example the team repo) is changed in place.
"""
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

SHIM = '''/* Generated by tools/export_to_template.py. Do not edit. */
#include "main_glasses.h"
#include "../app.h"

EXPORT ER subsystem5_init(void)
{
	return main_glasses_init();
}

EXPORT ER subsystem5_start(void)
{
	return main_glasses_start();
}

#if APP_TEST
EXPORT void subsystem5_test(void)
{
	tm_printf((UB*)"subsystem5_test: host tests cover the radar code\\n");
}
#endif
'''


def main() -> int:
    if len(sys.argv) > 1:
        template = pathlib.Path(sys.argv[1])
    else:
        template = ROOT / "build" / "utkernel"
        shutil.rmtree(template, ignore_errors=True)
        shutil.copytree(ROOT / "soup" / "utkernel", template)
    if not (template / "app_program" / "app.h").exists():
        print("not a course template root:", template)
        return 2
    dest = template / "app_program" / "subsystem5"
    dest.mkdir(parents=True, exist_ok=True)
    for old in list(dest.glob("*.c")) + list(dest.glob("*.h")):
        old.unlink()
    names = {}
    for folder in ("src", "config"):
        for path in sorted((ROOT / folder).rglob("*")):
            if path.suffix not in (".c", ".h"):
                continue
            if path.name in names:
                print("name clash:", path, names[path.name])
                return 1
            names[path.name] = path
            shutil.copy2(path, dest / path.name)
    (dest / "subsystem5.c").write_text(SHIM)
    cfg = template / "config" / "config_device.h"
    text = cfg.read_text(encoding="utf-8")
    text = re.sub(r"(#define DEVCNF_USE_SER\s+)1", r"\g<1>0", text)
    cfg.write_text(text, encoding="utf-8")
    print("copied", len(names), "files + shim to", dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
